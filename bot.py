def scheduler_loop():
    """
    Фоновый цикл, каждые 10 минут проверяет базу
    и отправляет отложенные сообщения.
    """
    while True:
        try:
            ts = now_ts()
            with sqlite3.connect(DB) as c:
                # 1. ПЕРВЫЙ ДОЖИМ неоплативших (через FOLLOWUP_UNPAID_HOURS)
                unpaid = c.execute('''
                    SELECT user_id, arcane FROM users
                    WHERE paid=0 AND followup_sent=0
                    AND offer_ts>0 AND ?-offer_ts >= ?
                ''', (ts, FOLLOWUP_UNPAID_HOURS*3600)).fetchall()
                for uid, arc in unpaid:
                    followup_unpaid(uid, arc)
                    c.execute('UPDATE users SET followup_sent=1 WHERE user_id=?', (uid,))

                # 2. ВТОРОЙ ДОЖИМ неоплативших (через FOLLOWUP2_UNPAID_HOURS, после первого)
                unpaid2 = c.execute('''
                    SELECT user_id, arcane FROM users
                    WHERE paid=0 AND followup_sent=1 AND followup2_sent=0
                    AND offer_ts>0 AND ?-offer_ts >= ?
                ''', (ts, FOLLOWUP2_UNPAID_HOURS*3600)).fetchall()
                for uid, arc in unpaid2:
                    followup_unpaid_2(uid, arc)
                    c.execute('UPDATE users SET followup2_sent=1 WHERE user_id=?', (uid,))

                # 3. АПСЕЛ после оплаты (через 30 минут, пока человек горячий)
                hot = c.execute('''
                    SELECT user_id, arcane FROM users
                    WHERE paid=1 AND upsell_sent=0
                    AND paid_ts>0 AND ?-paid_ts >= ?
                ''', (ts, 30*60)).fetchall()
                for uid, arc in hot:
                    offer_upsell(uid, arc)
                    c.execute('UPDATE users SET upsell_sent=1 WHERE user_id=?', (uid,))

                # 4. ПРОГРЕВ день 2 (через NURTURE_DAY2_HOURS после оплаты)
                nurture2 = c.execute('''
                    SELECT user_id, arcane FROM users
                    WHERE paid=1 AND nurture2_sent=0
                    AND paid_ts>0 AND ?-paid_ts >= ?
                ''', (ts, NURTURE_DAY2_HOURS*3600)).fetchall()
                for uid, arc in nurture2:
                    send_nurture_day2(uid, arc)
                    c.execute('UPDATE users SET nurture2_sent=1 WHERE user_id=?', (uid,))

                # 5. ПРОГРЕВ день 4 (через NURTURE_DAY4_HOURS после оплаты)
                nurture4 = c.execute('''
                    SELECT user_id, arcane FROM users
                    WHERE paid=1 AND nurture4_sent=0
                    AND paid_ts>0 AND ?-paid_ts >= ?
                ''', (ts, NURTURE_DAY4_HOURS*3600)).fetchall()
                for uid, arc in nurture4:
                    send_nurture_day4(uid, arc)
                    c.execute('UPDATE users SET nurture4_sent=1 WHERE user_id=?', (uid,))

                # 6. КОНСУЛЬТАЦИЯ оплатившим (через CONSULT_AFTER_DAYS)
                paid = c.execute('''
                    SELECT user_id, arcane FROM users
                    WHERE paid=1 AND consult_sent=0
                    AND paid_ts>0 AND ?-paid_ts >= ?
                ''', (ts, CONSULT_AFTER_DAYS*86400)).fetchall()
                for uid, arc in paid:
                    offer_consultation(uid, arc)
                    c.execute('UPDATE users SET consult_sent=1 WHERE user_id=?', (uid,))
        except Exception as e:
            log.error(f"Scheduler error: {e}")

        time.sleep(600)  # пауза 10 минут

