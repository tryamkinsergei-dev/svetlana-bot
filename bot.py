DB = os.getenv('DB_PATH', 'bot.db')

def now_ts():
    return int(time.time())

def init_db():
    with sqlite3.connect(DB) as c:
        c.execute('''CREATE TABLE IF NOT EXISTS users (
            user_id INTEGER PRIMARY KEY, arcane INTEGER,
            phone TEXT, payment_id TEXT, paid INTEGER DEFAULT 0,
            offer_ts INTEGER DEFAULT 0,
            paid_ts INTEGER DEFAULT 0,
            followup_sent INTEGER DEFAULT 0,
            followup2_sent INTEGER DEFAULT 0,
            consult_sent INTEGER DEFAULT 0,
            upsell_sent INTEGER DEFAULT 0,
            upsell_payment_id TEXT,
            upsell_paid INTEGER DEFAULT 0,
            nurture2_sent INTEGER DEFAULT 0,
            nurture4_sent INTEGER DEFAULT 0)''')
    # Миграция: добавляем колонки если база старая
    with sqlite3.connect(DB) as c:
        cols = [r[1] for r in c.execute("PRAGMA table_info(users)").fetchall()]
        for col, default in [('offer_ts','0'),('paid_ts','0'),
                             ('followup_sent','0'),('followup2_sent','0'),
                             ('consult_sent','0'),('upsell_sent','0'),
                             ('upsell_paid','0'),('nurture2_sent','0'),
                             ('nurture4_sent','0')]:
            if col not in cols:
                c.execute(f'ALTER TABLE users ADD COLUMN {col} INTEGER DEFAULT {default}')
        # текстовая колонка отдельно
        if 'upsell_payment_id' not in cols:
            c.execute('ALTER TABLE users ADD COLUMN upsell_payment_id TEXT')
    # Таблица событий для аналитики воронки (с временными метками)
    with sqlite3.connect(DB) as c:
        c.execute('''CREATE TABLE IF NOT EXISTS events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER,
            event TEXT,
            ts INTEGER)''')
        # Индекс для быстрых выборок по событию и времени
        c.execute('CREATE INDEX IF NOT EXISTS idx_events ON events(event, ts)')

def log_event(user_id, event):
    """Фиксируем шаг воронки. Каждый шаг для юзера считаем один раз."""
    try:
        with sqlite3.connect(DB) as c:
            # Уникальность: один тип события на юзера записываем единожды
            exists = c.execute(
                'SELECT 1 FROM events WHERE user_id=? AND event=? LIMIT 1',
                (user_id, event)).fetchone()
            if not exists:
                c.execute('INSERT INTO events (user_id, event, ts) VALUES (?,?,?)',
                          (user_id, event, now_ts()))
    except Exception as e:
        log.error(f"log_event error: {e}")

