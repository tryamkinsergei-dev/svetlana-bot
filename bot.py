@flask_app.route('/yukassa/callback', methods=['POST'])
def yukassa_callback():
    try:
        data = request.json
        if data.get('event') == 'payment.succeeded':
            obj = data.get('object', {})
            pid = obj.get('id')
            product = obj.get('metadata', {}).get('product', 'video')
            if pid:
                if product == 'upsell':
                    # Оплачен апсел (полный разбор)
                    row = db_find_by_upsell_payment(pid)
                    if row:
                        uid, arc, _phone = row
                        db_mark_upsell_paid(uid)
                        threading.Thread(target=deliver_upsell_confirmation,
                                         args=(uid, arc), daemon=True).start()
                else:
                    # Оплачено видео (трипваер)
                    row = db_find_by_payment(pid)
                    if row:
                        uid, arc = row
                        db_mark_paid(uid)
                        threading.Thread(target=deliver_video,
                                         args=(uid, arc), daemon=True).start()
        return jsonify({'status': 'ok'})
    except Exception as e:
        log.error(f"Webhook error: {e}")
        return jsonify({'status': 'error'}), 500

