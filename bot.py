async def cmd_stats(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Аналитика воронки. Только для админов."""
    uid = update.effective_user.id
    if uid not in ADMIN_IDS:
        return

    ts = now_ts()
    day_ago  = ts - 86400
    week_ago = ts - 7*86400

    def count(event, since=0):
        with sqlite3.connect(DB) as c:
            return c.execute(
                'SELECT COUNT(DISTINCT user_id) FROM events WHERE event=? AND ts>=?',
                (event, since)).fetchone()[0]

    def pct(a, b):
        return f"{round(a/b*100)}%" if b else "0%"

    def block(title, since):
        s = count('start', since)
        o = count('offer', since)
        p = count('phone', since)
        v = count('paid_video', since)
        u = count('paid_upsell', since)
        money = v*PRICE + u*UPSELL_PRICE
        return "\n".join([
            f"<b>{title}</b>",
            f"Зашли в бота: {s}",
            f"Рассчитали звезду: {o}  ({pct(o,s)} от входов)",
            f"Оставили телефон: {p}  ({pct(p,o)} от расчёта)",
            f"Купили видео: {v}  ({pct(v,p)} от телефонов)",
            f"Купили разбор: {u}  ({pct(u,v)} от видео)",
            f"Выручка: {money} ₽",
        ])

    text = (
        block("📊 За всё время", 0) + "\n\n" +
        block("📅 За 7 дней", week_ago) + "\n\n" +
        block("🔥 Сегодня", day_ago) + "\n\n" +
        "<i>Воронка: вход → расчёт звезды → телефон → видео 990 → разбор 4900</i>"
    )
    await update.message.reply_text(text, parse_mode='HTML')

def main():
    if not BOT_TOKEN:
        raise RuntimeError("BOT_TOKEN не задан!")
    init_db()
    threading.Thread(target=run_flask, daemon=True).start()
    log.info(f"Flask на порту {PORT}")
    # Запускаем планировщик допродаж
    threading.Thread(target=scheduler_loop, daemon=True).start()
    log.info("Планировщик допродаж запущен")
    app = Application.builder().token(BOT_TOKEN).build()
    app.add_handler(CommandHandler('start', cmd_start))
    app.add_handler(CommandHandler('stats', cmd_stats))
    app.add_handler(MessageHandler(filters.CONTACT, handle_contact))
    app.add_handler(MessageHandler(filters.StatusUpdate.WEB_APP_DATA, handle_webapp_data))
    app.add_handler(MessageHandler(filters.VIDEO | filters.Document.ALL, handle_file))
    # Текстовые сообщения, последним чтобы не перехватывал команды
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_text))
    log.info("Бот запускается... ✦")
    app.run_polling(allowed_updates=Update.ALL_TYPES)

if __name__ == '__main__':
    main()
